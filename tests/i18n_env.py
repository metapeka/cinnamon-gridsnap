#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Исходный язык интерфейса для тестов.

Строки в коде русские, а поверх них ложатся каталоги `en`/`zh_CN`; язык
выбирается из локали машины, и `LANG=en_US.UTF-8` (как в CI и на многих
машинах) означает английский. Тесты проверяют поведение, а не перевод, и
сверяются с русскими сообщениями прямо из кода, поэтому им нужен исходный
язык — один и тот же на любой машине.

Подключается одной строкой в начале модуля:

    import i18n_env  # noqa: F401  (тесты идут на исходном языке)

Переменная не перетирается, если `GRIDSNAP_LANG` уже выставлен снаружи: так
работает и `GRIDSNAP_LANG=en python3 -m unittest discover -s tests`, и тесты
выбора языка в `test_zone_i18n.py`.
"""

import os

os.environ.setdefault("GRIDSNAP_LANG", "ru")
